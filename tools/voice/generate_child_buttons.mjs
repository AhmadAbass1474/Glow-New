async function supabaseRows(table, select) {
  const response = await fetch(
    `${supabaseUrl}/rest/v1/${table}?select=${encodeURIComponent(select)}`,
    {
      headers: {
        apikey: supabaseKey,
        Authorization: `Bearer ${supabaseKey}`,
      },
    },
  );
  if (!response.ok) {
    console.error('supabase', table, response.status, await response.text());
    return [];
  }
  return response.json();
}

function fileId(phrase) {
  return createHash('sha1').update(phrase).digest('hex').slice(0, 12);
}

