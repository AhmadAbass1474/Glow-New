const questions = await supabaseRows('questions', 'options');
const phrases = new Set(staticPhrases);
for (const row of worlds) if (row.title) phrases.add(String(row.title).trim());
for (const row of missions) if (row.title) phrases.add(String(row.title).trim());
for (const row of questions) {
  const options = Array.isArray(row.options) ? row.options : [];
  for (const option of options) {
    const text = String(option).trim();
    if (text) phrases.add(text);
  }
}

const unique = [...phrases];
